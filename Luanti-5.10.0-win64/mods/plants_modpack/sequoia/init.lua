-- Nodes

core.register_node("sequoia:sapling", {
	description = S("Giant Sequoia Tree Sapling"),
	drawtype = "plantlike",
	tiles = {"sequoia_sapling.png"},
	inventory_image = "sequoia_sapling.png",
	paramtype = "light",
	sunlight_propagates = true,
	walkable = false,
	on_timer = grow_sequoia_tree,
	selection_box = {
		type = "fixed",
		fixed = {-4/16, -0.5, -4/16, 4/16, 7/16, 4/16}
	},
	groups = {snappy = 2, dig_immediate = 3, flammable = 2, attached_node = 1, sapling = 1},
	sounds = default.node_sound_leaves_defaults(),

	on_construct = function(pos)
		core.get_node_timer(pos):start(math.random(600, 3000))
	end,

	on_place = function(itemstack, placer, pointd)
		itemstack = default.sapling_on_place(itemstack, placer, pointd,
			"sequoia:sapling",
			-- minp, maxp to be checked, relative to sapling pos
			-- minp_relative.y = 1 because sapling pos has been checked
			{x = -9, y = 1, z = -9},
			{x = 9, y = 40, z = 9},
			-- maximum interval of interior volume check
			4)

		return itemstack
	end,
	grown_height = 39,
})

